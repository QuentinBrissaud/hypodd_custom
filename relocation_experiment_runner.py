#!/usr/bin/env python
"""
Run batches of HypoDDPy relocations from config-file variants.

The intended notebook pattern is:

    base_config = "example_hypodd_config.ini"
    experiments = [
        RelocationExperiment(
            name="maxsep_5_obs12_damp30",
            overrides={
                "ph2dt.MAXSEP": 5,
                "hypodd.OBSCT": 12,
                "hypodd.ITERATIONS": [
                    "100 0 0 -999 -999 0.1 0.05 6 -999 30",
                ],
            },
        ),
        RelocationExperiment(
            name="maxsep_10_obs25_damp10",
            overrides={
                "ph2dt.MAXSEP": 10,
                "hypodd.OBSCT": 25,
                "hypodd.ITERATIONS": [
                    "100 0 0 -999 -999 0.1 0.05 6 -999 10",
                ],
            },
        ),
    ]

    summary = run_relocation_experiments(
        experiments=experiments,
        base_config_file=base_config,
        output_root="experiment_runs",
        event_files=["events.xml"],
        station_files=["stations.xml"],
        velocity_model={
            "model_type": "layered_variable_vp_vs_ratio",
            "layer_tops": [
                (-10.00, 5.80, 5.80 / 1.73),
                (100.90, 8.32, 8.32 / 4.61),
            ],
        },
    )

Each experiment gets its own folder containing:

    config.ini
    relocated_events.xml
    run_status.json
    HypoDDPy input/output files generated by the relocation
"""

from dataclasses import dataclass, field
from pathlib import Path
import configparser
import copy
import json
import os
import re
import shutil
import traceback


@dataclass
class RelocationExperiment:
    """
    One relocation setup.

    ``overrides`` can be either nested:

        {"ph2dt": {"MAXSEP": 5}, "hypodd": {"OBSCT": 12}}

    or dotted:

        {"ph2dt.MAXSEP": 5, "hypodd.OBSCT": 12}

    Values are written to the generated INI file. For multi-line HypoDD
    iteration rows, pass a list or tuple of row strings.
    """

    name: str
    overrides: dict = field(default_factory=dict)
    description: str = ""
    velocity_model: dict | None = None
    use_cross_correlation: bool | None = None
    waveform_files: list[str] | None = None
    create_plots: bool = False
    skip_if_output_exists: bool = True


def _safe_name(name):
    name = str(name).strip()
    if not name:
        raise ValueError("Experiment name cannot be empty.")
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", name)


def _as_list(value):
    if value is None:
        return []
    if isinstance(value, (str, os.PathLike)):
        return [str(value)]
    return [str(item) for item in value]


def _format_config_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return "\n    " + "\n    ".join(str(item) for item in value)
    return str(value)


def _normalize_overrides(overrides):
    normalized = {}
    for key, value in (overrides or {}).items():
        if isinstance(value, dict):
            section = str(key)
            normalized.setdefault(section, {})
            for option, nested_value in value.items():
                normalized[section][str(option)] = nested_value
            continue
        if isinstance(key, tuple) and len(key) == 2:
            section, option = key
        elif isinstance(key, str) and "." in key:
            section, option = key.split(".", 1)
        else:
            raise ValueError(
                "Override keys must be section.option, (section, option), "
                "or nested dictionaries. Got %r." % (key,)
            )
        normalized.setdefault(str(section), {})[str(option)] = value
    return normalized


def build_config_variant(base_config_file, output_config_file, overrides):
    """
    Create one generated config file from a base INI plus overrides.

    Returns the ``ConfigParser`` object that was written.
    """
    parser = configparser.ConfigParser()
    parser.optionxform = str
    read_files = parser.read(str(base_config_file))
    if not read_files:
        raise FileNotFoundError("Could not read base config: %s" % base_config_file)

    for section, options in _normalize_overrides(overrides).items():
        if not parser.has_section(section):
            parser.add_section(section)
        for option, value in options.items():
            parser.set(section, option, _format_config_value(value))

    output_config_file = Path(output_config_file)
    output_config_file.parent.mkdir(parents=True, exist_ok=True)
    with output_config_file.open("w", encoding="utf-8") as handle:
        handle.write(
            "# Generated by relocation_experiment_runner.py\n"
            "# Base config: %s\n\n" % base_config_file
        )
        parser.write(handle)
    return parser


def default_relocator_factory(working_dir):
    from hypoddpy.hypodd_relocator import HypoDDRelocator

    return HypoDDRelocator(working_dir=str(working_dir))


def _apply_velocity_model(relocator, velocity_model):
    if velocity_model is None:
        return
    velocity_model = copy.deepcopy(velocity_model)
    model_type = velocity_model.pop("model_type")
    relocator.setup_velocity_model(model_type=model_type, **velocity_model)


def _summarize_output_files(working_dir):
    working_dir = Path(working_dir)
    output_files = working_dir / "output_files"
    input_files = working_dir / "input_files"
    summary = {
        "hypodd_reloc_exists": (output_files / "hypoDD.reloc").exists(),
        "hypodd_loc_exists": (output_files / "hypoDD.loc").exists(),
        "dt_ct_exists": (input_files / "dt.ct").exists(),
        "dt_cc_exists": (input_files / "dt.cc").exists(),
        "relocated_event_count": None,
    }
    reloc_file = output_files / "hypoDD.reloc"
    if reloc_file.exists():
        with reloc_file.open("r", encoding="utf-8", errors="replace") as handle:
            summary["relocated_event_count"] = sum(
                1 for line in handle if line.strip()
            )
    return summary


def run_single_relocation_experiment(
    experiment,
    base_config_file,
    output_root,
    event_files,
    station_files,
    waveform_files=None,
    velocity_model=None,
    relocator_factory=default_relocator_factory,
    output_event_filename="relocated_events.xml",
):
    """
    Run one experiment and return a status dictionary.
    """
    experiment_name = _safe_name(experiment.name)
    working_dir = Path(output_root) / experiment_name
    working_dir.mkdir(parents=True, exist_ok=True)

    config_file = working_dir / "config.ini"
    overrides = copy.deepcopy(experiment.overrides)
    if experiment.use_cross_correlation is not None:
        overrides.setdefault("relocator", {})
        overrides["relocator"]["use_cross_correlation"] = (
            experiment.use_cross_correlation
        )
    build_config_variant(base_config_file, config_file, overrides)

    status = {
        "name": experiment.name,
        "working_dir": str(working_dir),
        "config_file": str(config_file),
        "output_event_file": str(working_dir / output_event_filename),
        "description": experiment.description,
        "status": "not_started",
        "error": None,
        "traceback": None,
        "outputs": {},
    }
    status_file = working_dir / "run_status.json"
    output_event_file = working_dir / output_event_filename

    if experiment.skip_if_output_exists and output_event_file.exists():
        status["status"] = "skipped_existing_output"
        status["outputs"] = _summarize_output_files(working_dir)
        with status_file.open("w", encoding="utf-8") as handle:
            json.dump(status, handle, indent=2)
        return status

    try:
        relocator = relocator_factory(working_dir)
        relocator.load_configuration_file(str(config_file))
        relocator.add_event_files(_as_list(event_files))
        relocator.add_station_files(_as_list(station_files))

        chosen_waveform_files = (
            experiment.waveform_files
            if experiment.waveform_files is not None
            else waveform_files
        )
        if chosen_waveform_files:
            relocator.add_waveform_files(_as_list(chosen_waveform_files))

        chosen_velocity_model = (
            experiment.velocity_model
            if experiment.velocity_model is not None
            else velocity_model
        )
        _apply_velocity_model(relocator, chosen_velocity_model)

        relocator.start_relocation(
            output_event_file=str(output_event_file),
            create_plots=experiment.create_plots,
        )
        status["status"] = "success"
        status["outputs"] = _summarize_output_files(working_dir)
    except Exception as exc:
        status["status"] = "failed"
        status["error"] = "%s: %s" % (exc.__class__.__name__, exc)
        status["traceback"] = traceback.format_exc()

    with status_file.open("w", encoding="utf-8") as handle:
        json.dump(status, handle, indent=2)
    return status


def run_relocation_experiments(
    experiments,
    base_config_file,
    output_root,
    event_files,
    station_files,
    waveform_files=None,
    velocity_model=None,
    relocator_factory=default_relocator_factory,
    output_event_filename="relocated_events.xml",
    stop_on_failure=False,
    overwrite=False,
):
    """
    Run several relocation experiments in sequence.

    Returns a list of status dictionaries. If pandas is installed, you can turn
    it into a table with ``pandas.DataFrame(summary)``.
    """
    output_root = Path(output_root)
    output_root.mkdir(parents=True, exist_ok=True)
    all_status = []

    for experiment in experiments:
        if overwrite:
            working_dir = output_root / _safe_name(experiment.name)
            if working_dir.exists():
                shutil.rmtree(working_dir)
        status = run_single_relocation_experiment(
            experiment=experiment,
            base_config_file=base_config_file,
            output_root=output_root,
            event_files=event_files,
            station_files=station_files,
            waveform_files=waveform_files,
            velocity_model=velocity_model,
            relocator_factory=relocator_factory,
            output_event_filename=output_event_filename,
        )
        all_status.append(status)
        if stop_on_failure and status["status"] == "failed":
            break

    summary_file = output_root / "experiment_summary.json"
    with summary_file.open("w", encoding="utf-8") as handle:
        json.dump(all_status, handle, indent=2)
    return all_status

